export function guessCategory(name) {
  const n = normName(name);
  if (SEASONING_PRESETS.some((s) => normName(s) === n)) return '調味料';
  for (const [cat, words] of CATEGORY_WORDS) {
    if (words.some((w) => n.includes(normName(w)))) return cat;
  }
  return '野菜';
}

