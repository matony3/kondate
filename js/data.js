export function proteinOptions() {
  const out = [];
  for (const g of PROTEINS) {
    for (const it of g.items) {
      out.push({
        kind: g.kind,
        type: g.type,
        cut: it.cut,
        key: `${g.kind}:${g.type}:${it.cut}`,
        label: g.kind === 'fish' || g.type === it.cut ? it.cut : `${g.type}（${it.cut}）`,
        kw: it.kw.map((set) => set.map(normName)),
      });
    }
  }
  return out;
}

export function findProtein(key) {
  return proteinOptions().find((o) => o.key === key) || null;
}

